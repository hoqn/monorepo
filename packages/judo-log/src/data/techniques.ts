const BY_ID = new Map(TECHNIQUES.map((t) => [t.id, t]));

export function byId(id: string): Technique | undefined {
  return BY_ID.get(id);
}

/**
 * 한국어 정식명 · 별칭 · 일본어 · 로마자 · 한자를 전부 매칭한다.
 * 사범님이 뭐라고 부르든 찾아져야 하고, 한쪽만 물면 "내 기술이 앱에 없네" 하고 이탈한다.
 */
export function searchTechniques(query: string): Technique[] {
  const needle = query.trim().toLowerCase();
  if (needle === '') return [];
  return TECHNIQUES.filter((t) =>
    [t.ko, t.jp, t.romaji, t.kanji, ...t.aliases].some((name) => name.toLowerCase().includes(needle)),
  );
}
